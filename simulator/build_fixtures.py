"""Regenerate fixtures/zones.geojson and supabase/seed.sql from fixtures/zones.json.

Run from the repo root:  python simulator/build_fixtures.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "fixtures" / "zones.json").read_text())


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def build_seed() -> str:
    out = ["-- GENERATED by simulator/build_fixtures.py from fixtures/zones.json. Do not edit by hand.",
           "truncate impacts, event, parking_session, zone_status, rate_rule, zone, facility, operator, destination restart identity cascade;", ""]
    for o in DATA["operators"]:
        out.append(f"insert into operator values ({o['id']}, {q(o['name'])}, {q(o['pay_app'])});")
    for f in DATA["facilities"]:
        out.append(f"insert into facility values ({f['id']}, {f['operator_id']}, {q(f['name'])}, {q(f['type'])}, {f['lat']}, {f['lng']});")
    for z in DATA["zones"]:
        out.append(
            f"insert into zone values ({z['id']}, {z['facility_id']}, {q(z['name'])}, {z['capacity']}, "
            f"{q(z['visitor_allowed'])}, {z['demand']}, {q(z['profile'])});")
    for zone_id, rules in DATA["rate_templates"].items():
        if zone_id.startswith("_"):
            continue
        for r in rules:
            for d in r["days"]:
                out.append(
                    "insert into rate_rule (zone_id, day_of_week, start_time, end_time, hourly_rate, time_limit_min) "
                    f"values ({zone_id}, {d}, {q(r['start'])}, {q(r['end'])}, {r['rate']}, {q(r['limit'])});")
    for d in DATA["destinations"]:
        out.append(f"insert into destination values ({d['id']}, {q(d['name'])}, {d['lat']}, {d['lng']});")
    out.append("insert into zone_status (zone_id) select zone_id from zone;")
    return "\n".join(out) + "\n"


def build_geojson() -> dict:
    fac = {f["id"]: f for f in DATA["facilities"]}
    ops = {o["id"]: o for o in DATA["operators"]}
    features = []
    for z in DATA["zones"]:
        f = fac[z["facility_id"]]
        rules = DATA["rate_templates"].get(str(z["id"]), [])
        first = rules[0] if rules else {}
        features.append({
            "type": "Feature",
            "geometry": {"type": "Point", "coordinates": [f["lng"], f["lat"]]},
            "properties": {
                "zone_id": z["id"],
                "name": z["name"],
                "facility": f["name"],
                "facility_type": f["type"],
                "operator": ops[f["operator_id"]]["name"],
                "pay_app": ops[f["operator_id"]]["pay_app"],
                "capacity": z["capacity"],
                "visitor_allowed": z["visitor_allowed"],
                "hourly_rate": first.get("rate"),
                "time_limit_min": first.get("limit"),
            },
        })
    return {"type": "FeatureCollection", "features": features}


if __name__ == "__main__":
    (ROOT / "supabase" / "seed.sql").write_text(build_seed())
    (ROOT / "fixtures" / "zones.geojson").write_text(json.dumps(build_geojson(), indent=2) + "\n")
    print("wrote supabase/seed.sql and fixtures/zones.geojson")
